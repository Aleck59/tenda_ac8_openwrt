void
odm_config_mp_8814c_extra_agc_tab(struct dm_struct *dm, enum odm_rf_band band)
{
	u32	i = 0;
	u8	c_cond;
	boolean	is_matched = true, is_skipped = false;
	u32	array_len = 0;
	u32	*array = NULL;

	u32	v1 = 0, v2 = 0, pre_v1 = 0, pre_v2 = 0;
	u32	a1 = 0, a2 = 0, a3 = 0, a4 = 0;

	PHYDM_DBG(dm, ODM_COMP_INIT, "===> %s\n", __func__);

	if (dm->rfe_type == 0) {
		switch (band) {
		case ODM_RF_BAND_2G:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe0, _tab67, _2g)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe0, _tab67, _2g);
			break;
		case ODM_RF_BAND_5G_LOW:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gl)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gl);
			break;
		case ODM_RF_BAND_5G_MID:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gm)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gm);
			break;
		case ODM_RF_BAND_5G_HIGH:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gh)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe0, _tab67, _5gh);
			break;
		default:
			return;
		}
	}else if (dm->rfe_type == 1) {
		switch (band) {
		case ODM_RF_BAND_2G:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe1, _tab67, _2g)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe1, _tab67, _2g);
			break;
		case ODM_RF_BAND_5G_LOW:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gl)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gl);
			break;
		case ODM_RF_BAND_5G_MID:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gm)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gm);
			break;
		case ODM_RF_BAND_5G_HIGH:
			array_len = sizeof(AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gh)) /
					   sizeof(u32);
			array = (u32 *)AGC_TAB_8814C(_cuta, _rfe1, _tab67, _5gh);
			break;
		default:
			return;
		}
	}

	while ((i + 1) < array_len) {
		v1 = array[i];
		v2 = array[i + 1];

		if (v1 & (BIT(31) | BIT(30))) {/*positive & negative condition*/
			if (v1 & BIT(31)) {/* positive condition*/
				c_cond  =
					(u8)((v1 & (BIT(29) | BIT(28))) >> 28);
				if (c_cond == COND_ENDIF) {/*end*/
					is_matched = true;
					is_skipped = false;
					PHYDM_DBG(dm, ODM_COMP_INIT, "ENDIF\n");
				} else if (c_cond == COND_ELSE) { /*else*/
					is_matched = is_skipped ? false : true;
					PHYDM_DBG(dm, ODM_COMP_INIT, "ELSE\n");
				} else {/*if , else if*/
					pre_v1 = v1;
					pre_v2 = v2;
					PHYDM_DBG(dm, ODM_COMP_INIT,
						  "IF or ELSE IF\n");
				}
			} else if (v1 & BIT(30)) { /*negative condition*/
				if (!is_skipped) {
					a1 = pre_v1; a2 = pre_v2;
					a3 = v1; a4 = v2;
					if (check_positive(dm,
							   a1, a2, a3, a4)) {
						is_matched = true;
						is_skipped = true;
					} else {
						is_matched = false;
						is_skipped = false;
					}
				} else {
					is_matched = false;
				}
			}
		} else {
			if (is_matched)
				odm_config_bb_agc_8814c(dm, v1, MASKDWORD, v2);
		}
		i = i + 2;
	}
}

u32
odm_get_version_mp_8814c_extra_agc_tab(void)
{
		return 2;
}

